import type { Evolution } from "../domain/evolution";
import type { Species, SpeciesId } from "../domain/species";

import { EvolutionMethod } from "../domain/evolution";
import { GrowthRate } from "../domain/growth-rate";
import { Genre } from "../domain/species";
import { Stat } from "../domain/stat";
import { Type } from "../domain/type";

interface SpeciesTemplate {
	id: SpeciesId;
	number: number;
	size?: Species["size"];
	types: Species["types"];
	stats: Species["stats"];
	gender?: Species["gender"];
	baseExperience?: number;
	catchRate?: number;
	growthRate?: GrowthRate;
	evolutions?: Evolution[];
	learnset?: Species["learnset"];
}

const STARTER_GENDER = { [Genre.Male]: 87.5, [Genre.Female]: 12.5 };
const EVEN_GENDER = { [Genre.Male]: 50, [Genre.Female]: 50 };
const FEMALE_ONLY = { [Genre.Female]: 100 };
const MALE_ONLY = { [Genre.Male]: 100 };

/** Returns a stat block in the order expected by the engine. */
function createStats(
	hp: number,
	attack: number,
	defense: number,
	specialAttack: number,
	specialDefense: number,
	speed: number,
): Species["stats"] {
	return {
		[Stat.HP]: hp,
		[Stat.Attack]: attack,
		[Stat.Defense]: defense,
		[Stat.SpecialAttack]: specialAttack,
		[Stat.SpecialDefense]: specialDefense,
		[Stat.Speed]: speed,
	};
}

/** Creates a simple level-up evolution reference. */
function levelEvolution(speciesId: SpeciesId, level: number): Evolution {
	return { method: EvolutionMethod.Level, speciesId, level };
}

/** Creates a trade evolution reference without item requirements. */
function tradeEvolution(speciesId: SpeciesId): Evolution {
	return { method: EvolutionMethod.Trade, speciesId };
}

/** Normalizes authored roster entries into runtime species records. */
function createSpecies(template: SpeciesTemplate): Species {
	return {
		number: template.number,
		size: template.size ?? { weight: 100, height: 1 },
		types: template.types,
		gender: template.gender ?? EVEN_GENDER,
		baseExperience: template.baseExperience ?? 100,
		catchRate: template.catchRate ?? 45,
		growthRate: template.growthRate ?? GrowthRate.MediumFast,
		stats: template.stats,
		evolutions: template.evolutions ?? [],
		learnset: template.learnset ?? [],
	};
}

/** Builds the original Kanto roster keyed by species identifier. */
function createSpeciesIndex(entries: SpeciesTemplate[]): Record<SpeciesId, Species> {
	let species: Record<SpeciesId, Species> = {};

	for (let entry of entries) {
		species[entry.id] = createSpecies(entry);
	}

	return species;
}

