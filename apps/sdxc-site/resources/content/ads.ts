/**
 * The square ads the documentation right rail can show: Uptime landings, features,
 * use cases and monitor types, plus the React Router OAuth2 Handbook. The picker
 * rotates through this list; each entry is one tile a reader may see for a day.
 *
 * @author [Sergio Xalambrí](https://sergiodxa.com)
 * @copyright Sergio Xalambrí 2026
 */

/** Visual surface a tile paints; each maps to a fixed palette in the ad component. */
export type SidebarAdSurface =
	| "uptime-forest"
	| "uptime-steel"
	| "uptime-ink"
	| "uptime-amber"
	| "uptime-violet"
	| "uptime-lime"
	| "handbook-navy"
	| "handbook-charcoal"
	| "handbook-code"
	| "handbook-forest";

/** One square ad the docs rail may show under the table of contents. */
export interface SidebarAdDefinition {
	/** Stable id for tests, campaign attribution, and naming a tile in the catalogue. */
	id: string;
	/** Destination the tile opens; always an absolute URL on a product the author ships. */
	href: string;
	/** Small top label naming the kind of pitch (feature, landing, monitor type, …). */
	kicker: string;
	title: string;
	tagline: string;
	/** Short call-to-action kept on one line at the foot of the tile. */
	cta: string;
	surface: SidebarAdSurface;
	/**
	 * Face the title uses. Serif reads as a handbook cover; mono as an API plate;
	 * sans is the default for product pitches.
	 */
	titleFace?: "sans" | "serif" | "mono";
	/** Product family the tile belongs to; used when grouping the catalogue. */
	brand: "uptime" | "handbook";
}

