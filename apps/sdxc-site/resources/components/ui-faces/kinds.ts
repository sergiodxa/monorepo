/** Scene id a miniature paints. */
export type FaceKind = (typeof FACE_KIND)[keyof typeof FACE_KIND];

/** Resolves the miniature scene for a catalogue slug, falling back to a quiet card. */
export function faceKindFor(slug: string): FaceKind {
	return (FACE_KIND as Record<string, FaceKind>)[slug] ?? "card";
}
