/**
 * The umbrella generator over a fixture workspace: which packages it exposes, the module it
 * writes per subpath, wildcard expansion, conditions, stylesheets, and the failures it refuses
 * to paper over. The drift check against the real repo lives in `test/`.
 *
 * @author [Sergio Xalambrí](https://sergiodxa.com)
 * @copyright Sergio Xalambrí 2026
 */

import { mkdir, mkdtemp, rm, writeFile } from "node:fs/promises";
import { tmpdir } from "node:os";
import { dirname, join } from "node:path";

import { isFailure, unwrap } from "@sdxc/result";
import { afterEach, describe, expect, test } from "vitest";

import type { PackageManifest } from "../release/workspace.js";

import { generateUmbrella, umbrellaDrift, umbrellaManifest } from "./umbrella.js";

/** Fixture roots created by the current test, removed after it. */
const ROOTS: string[] = [];

afterEach(async () => {
	let created = ROOTS.splice(0);
	await Promise.all(created.map((root) => rm(root, { recursive: true, force: true })));
});

/** A fixture workspace holding `files`, keyed by path relative to its root. */
async function workspace(files: Record<string, string>): Promise<string> {
	let root = await mkdtemp(join(tmpdir(), "sdxc-umbrella-"));
	ROOTS.push(root);
	for (let [path, content] of Object.entries(files)) {
		await mkdir(dirname(join(root, path)), { recursive: true });
		await writeFile(join(root, path), content);
	}
	return root;
}

/** A `package.json` for `packages/<dir>` named `@sdxc/<dir>`, with any field overridden. */
function manifest(dir: string, fields: Partial<PackageManifest> = {}): string {
	return JSON.stringify({ name: `@sdxc/${dir}`, type: "module", ...fields });
}

/** The umbrella's own manifest in a fixture, which the generator ignores as a source. */
const UMBRELLA = {
	"packages/sdxc/package.json": JSON.stringify({ name: "sdxc", dependencies: {} }),
};

describe("generateUmbrella", () => {
	test("writes one re-export per subpath and maps it under the package directory", async () => {
		let root = await workspace({
			...UMBRELLA,
			"packages/markdown/package.json": manifest("markdown", {
				exports: { ".": "./src/index.ts", "./plugin/lint": "./src/plugin/lint.tsx" },
			}),
			"packages/markdown/src/index.ts": "export let parse = 1;\n",
			"packages/markdown/src/plugin/lint.tsx": "export function lint() {}\n",
		});

		let umbrella = unwrap(await generateUmbrella(root));

		expect(umbrella.exports).toEqual({
			"./markdown": "./src/markdown.ts",
			"./markdown/plugin/lint": "./src/markdown/plugin/lint.ts",
			"./config.schema.json": "./config.schema.json",
			"./lock.schema.json": "./lock.schema.json",
		});
		expect(umbrella.dependencies).toEqual(["@sdxc/markdown"]);
		expect(umbrella.files.get("src/markdown/plugin/lint.ts")).toBe(
			[
				"/**",
				" * `sdxc/markdown/plugin/lint`, the same module as `@sdxc/markdown/plugin/lint`. Generated by",
				" * `bun run sdxc:generate` from that package's export map.",
				" *",
				" * @author [Sergio Xalambrí](https://sergiodxa.com)",
				" * @copyright Sergio Xalambrí 2026",
				" */",
				"",
				'export * from "@sdxc/markdown/plugin/lint";',
				"",
			].join("\n"),
		);
	});

	test("forwards the default export of every module that has one", async () => {
		let root = await workspace({
			...UMBRELLA,
			"packages/i18n/package.json": manifest("i18n", {
				exports: {
					"./assignment": "./src/assignment.ts",
					"./declaration": "./src/declaration.ts",
					"./clause": "./src/clause.ts",
					"./none": "./src/none.ts",
				},
			}),
			"packages/i18n/src/assignment.ts": "export default 1;\n",
			"packages/i18n/src/declaration.ts": "export default function middleware() {}\n",
			"packages/i18n/src/clause.ts": "let a = 1;\nexport { a as default };\n",
			"packages/i18n/src/none.ts": 'export * from "./assignment.js";\nexport let b = 2;\n',
		});

		let { files } = unwrap(await generateUmbrella(root));

		for (let name of ["assignment", "declaration", "clause"]) {
			expect(files.get(`src/i18n/${name}.ts`)).toContain(
				`export { default } from "@sdxc/i18n/${name}";`,
			);
		}
		expect(files.get("src/i18n/none.ts")).not.toContain("default");
	});

	test("expands a wildcard into one module per published file and maps the pattern", async () => {
		let root = await workspace({
			...UMBRELLA,
			"packages/u/package.json": manifest("u", {
				exports: { "./color/*": "./src/color/*.ts" },
			}),
			"packages/u/src/color/bg.ts": "export let bg = 1;\n",
			"packages/u/src/color/bg.test.ts": "",
			"packages/u/src/color/accent.ts": "export let accent = 1;\n",
			"packages/u/src/color/nested/deep.ts": "export let deep = 1;\n",
			"packages/u/src/other.ts": "export let other = 1;\n",
		});

		let umbrella = unwrap(await generateUmbrella(root));

		expect(umbrella.exports["./u/color/*"]).toBe("./src/u/color/*.ts");
		expect([...umbrella.files.keys()].filter((path) => path.startsWith("src/")).sort()).toEqual([
			"src/u/color/accent.ts",
			"src/u/color/bg.ts",
			"src/u/color/nested/deep.ts",
		]);
		expect(umbrella.files.get("src/u/color/nested/deep.ts")).toContain(
			'export * from "@sdxc/u/color/nested/deep";',
		);
	});

	test("leaves out a wildcard whose pattern matches no file", async () => {
		let root = await workspace({
			...UMBRELLA,
			"packages/u/package.json": manifest("u", { exports: { "./size/*": "./src/size/*.ts" } }),
		});

		let umbrella = unwrap(await generateUmbrella(root));

		expect(umbrella.exports).toEqual({
			"./config.schema.json": "./config.schema.json",
			"./lock.schema.json": "./lock.schema.json",
		});
	});

	test("keeps conditions, writing one module per condition", async () => {
		let root = await workspace({
			...UMBRELLA,
			"packages/mocks/package.json": manifest("mocks", {
				exports: { "./sqlite": { bun: "./src/sqlite.bun.ts", default: "./src/sqlite.node.ts" } },
			}),
			"packages/mocks/src/sqlite.bun.ts": "export default 1;\n",
			"packages/mocks/src/sqlite.node.ts": "export let a = 1;\n",
		});

		let umbrella = unwrap(await generateUmbrella(root));

		expect(umbrella.exports["./mocks/sqlite"]).toEqual({
			bun: "./src/mocks/sqlite.bun.ts",
			default: "./src/mocks/sqlite.default.ts",
		});
		expect(umbrella.files.get("src/mocks/sqlite.bun.ts")).toContain("export { default }");
		expect(umbrella.files.get("src/mocks/sqlite.default.ts")).not.toContain("default }");
	});

	test("turns a stylesheet into a CSS file that imports it", async () => {
		let root = await workspace({
			...UMBRELLA,
			"packages/highlight/package.json": manifest("highlight", {
				exports: { "./styles.css": "./styles.css" },
			}),
		});

		let umbrella = unwrap(await generateUmbrella(root));

		expect(umbrella.exports["./highlight/styles.css"]).toBe("./src/highlight/styles.css");
		expect(umbrella.files.get("src/highlight/styles.css")).toMatch(
			/\*\/\n\n@import "@sdxc\/highlight\/styles\.css";\n$/,
		);
	});

	test("skips excluded and private packages and the umbrella itself", async () => {
		let root = await workspace({
			...UMBRELLA,
			"packages/spec/package.json": manifest("spec", { exports: { ".": "./src/index.ts" } }),
			"packages/internal/package.json": manifest("internal", {
				private: true,
				exports: { ".": "./src/index.ts" },
			}),
			"packages/result/package.json": manifest("result", { exports: { ".": "./src/index.ts" } }),
			"packages/result/src/index.ts": "export let ok = 1;\n",
		});

		let umbrella = unwrap(await generateUmbrella(root));

		expect(umbrella.dependencies).toEqual(["@sdxc/result"]);
		expect(Object.keys(umbrella.exports)).toEqual([
			"./result",
			"./config.schema.json",
			"./lock.schema.json",
		]);
	});

	test("emits the configuration schema as JSON Schema 2020-12", async () => {
		let root = await workspace(UMBRELLA);

		let schema = JSON.parse(
			unwrap(await generateUmbrella(root)).files.get("config.schema.json") ?? "",
		);

		expect(schema.$schema).toBe("https://json-schema.org/draft/2020-12/schema");
		expect(schema.properties.lock.default).toBe(".config/sdxc.lock.jsonl");
	});

	test("emits the lock file's entry schema as JSON Schema 2020-12", async () => {
		let root = await workspace(UMBRELLA);

		let schema = JSON.parse(
			unwrap(await generateUmbrella(root)).files.get("lock.schema.json") ?? "",
		);

		expect(schema.$schema).toBe("https://json-schema.org/draft/2020-12/schema");
		expect(schema.required).toEqual(["kind", "name"]);
	});

	test("forwards a package named cli beside the handwritten command line", async () => {
		let root = await workspace({
			...UMBRELLA,
			"packages/cli/package.json": manifest("cli", { exports: { ".": "./src/index.ts" } }),
			"packages/cli/src/index.ts": "export let a = 1;\n",
		});

		let umbrella = unwrap(await generateUmbrella(root));

		expect(umbrella.exports["./cli"]).toBe("./src/cli.ts");
		expect([...umbrella.files.keys()]).not.toContain("src/sdxc.ts");
	});

	test("refuses a target that is neither TypeScript nor CSS, and a fallback array", async () => {
		let json = await workspace({
			...UMBRELLA,
			"packages/data/package.json": manifest("data", { exports: { "./list": "./list.json" } }),
		});
		let array = await workspace({
			...UMBRELLA,
			"packages/data/package.json": manifest("data", {
				exports: { ".": ["./src/a.ts", "./src/b.ts"] },
			}),
		});

		let jsonResult = await generateUmbrella(json);
		let arrayResult = await generateUmbrella(array);

		expect(isFailure(jsonResult) && jsonResult.error.message).toBe(
			"@sdxc/data/list exports ./list.json, which is neither TypeScript nor CSS",
		);
		expect(isFailure(arrayResult) && arrayResult.error.message).toBe(
			"@sdxc/data exports a fallback array, which sdxc cannot forward",
		);
	});
});

describe("umbrellaManifest", () => {
	test("replaces the scoped dependencies and exports, keeping everything else", async () => {
		let root = await workspace({
			...UMBRELLA,
			"packages/result/package.json": manifest("result", { exports: { ".": "./src/index.ts" } }),
			"packages/result/src/index.ts": "export let ok = 1;\n",
		});
		let umbrella = unwrap(await generateUmbrella(root));

		let next = umbrellaManifest(
			{
				name: "sdxc",
				bin: { sdxc: "./src/sdxc.ts" },
				dependencies: { "@sdxc/gone": "workspace:*", left: "1.0.0" },
				peerDependencies: { remix: "3.0.0" },
			},
			umbrella,
		);

		expect(next).toEqual({
			name: "sdxc",
			bin: { sdxc: "./src/sdxc.ts" },
			exports: {
				"./result": "./src/result.ts",
				"./config.schema.json": "./config.schema.json",
				"./lock.schema.json": "./lock.schema.json",
			},
			dependencies: { "@sdxc/result": "workspace:*", left: "1.0.0" },
			peerDependencies: { remix: "3.0.0" },
		});
	});
});

describe("umbrellaDrift", () => {
	test("names every missing, outdated and stale file and every outdated manifest field", async () => {
		let root = await workspace({
			"packages/sdxc/package.json": JSON.stringify({
				name: "sdxc",
				exports: {},
				dependencies: {},
			}),
			"packages/sdxc/src/sdxc.ts": "",
			"packages/sdxc/src/gone/index.ts": "",
			"packages/sdxc/src/result.ts": "stale\n",
			"packages/result/package.json": manifest("result", {
				exports: { ".": "./src/index.ts", "./try": "./src/try.ts" },
			}),
			"packages/result/src/index.ts": "export let ok = 1;\n",
			"packages/result/src/try.ts": "export let attempt = 1;\n",
		});

		let problems = unwrap(await umbrellaDrift(root));

		expect(problems).toEqual([
			"config.schema.json is missing",
			"lock.schema.json is missing",
			"package.json dependencies are out of date",
			"package.json exports are out of date",
			"src/gone/index.ts backs no export subpath",
			"src/result.ts is out of date",
			"src/result/try.ts is missing",
		]);
	});
});
