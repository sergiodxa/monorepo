/**
 * Codegen script that reads Lucide's framework-agnostic icon data from
 * `lucide-static` and emits `src/registry.ts` (one named export per icon's
 * raw node data), `src/icon-names.ts` (the kebab-case name -> registry export
 * name lookup) and `src/index.ts`, which defines every icon's `remix/component` component.
 * Re-run with `bun run generate` whenever `lucide-static` is upgraded.
 *
 * @author [Sergio Xalambrí](https://sergiodxa.com)
 * @copyright Sergio Xalambrí 2026
 */

import { writeFile } from "node:fs/promises";
import path from "node:path";

import iconNodes from "lucide-static/icon-nodes.json" with { type: "json" };

/** A single Lucide icon's `[tag, attrs]` tuples, as shaped by `lucide-static`'s JSON data. */
type RawIconNode = ReadonlyArray<readonly [string, Record<string, string>]>;

/** Identifiers that are reserved words in JS modules, so can't be used as an `export const` name (e.g. the `"delete"` icon). */
const RESERVED_EXPORT_NAMES = new Set([
	"break",
	"case",
	"catch",
	"class",
	"const",
	"continue",
	"debugger",
	"default",
	"delete",
	"do",
	"else",
	"export",
	"extends",
	"false",
	"finally",
	"for",
	"function",
	"if",
	"import",
	"in",
	"instanceof",
	"new",
	"null",
	"return",
	"super",
	"switch",
	"this",
	"throw",
	"true",
	"try",
	"typeof",
	"var",
	"void",
	"while",
	"with",
	"yield",
	"let",
	"static",
	"enum",
	"await",
	"implements",
	"package",
	"protected",
	"interface",
	"private",
	"public",
]);

const PACKAGE_ROOT = path.resolve(import.meta.dirname, "..");
const INDEX_FILE = path.join(PACKAGE_ROOT, "src", "index.ts");
const REGISTRY_FILE = path.join(PACKAGE_ROOT, "src", "registry.ts");
const ICON_NAMES_FILE = path.join(PACKAGE_ROOT, "src", "icon-names.ts");
const FILE_HEADER = `/**
 * Generated by \`bun run generate\` from Lucide's icon data. Do not edit by hand.
 *
 * @author [Sergio Xalambrí](https://sergiodxa.com)
 * @copyright Sergio Xalambrí 2026
 */
`;

/** Converts a kebab-case icon name (e.g. `"circle-alert"`) into PascalCase (e.g. `"CircleAlert"`). */
function toPascalCase(iconName: string) {
	return iconName
		.split("-")
		.map((part) => part.charAt(0).toUpperCase() + part.slice(1))
		.join("");
}

/** Converts a kebab-case icon name (e.g. `"circle-alert"`) into camelCase (e.g. `"circleAlert"`). */
function toCamelCase(iconName: string) {
	let pascal = toPascalCase(iconName);
	return pascal.charAt(0).toLowerCase() + pascal.slice(1);
}

/**
 * The valid `registry.ts` export name for an icon's camelCase name, renamed
 * with a `Node` suffix when it would otherwise collide with a JS reserved
 * word (e.g. the `"delete"` and `"import"` icons).
 */
function toRegistryExportName(iconName: string) {
	let camel = toCamelCase(iconName);
	return RESERVED_EXPORT_NAMES.has(camel) ? `${camel}Node` : camel;
}

/** Renders an icon's `[tag, attrs]` tuples as a TypeScript array literal. */
function renderIconNode(iconNode: RawIconNode) {
	let entries = iconNode.map(
		([tag, attrs]) => `\t[${JSON.stringify(tag)}, ${JSON.stringify(attrs)}]`,
	);
	return `[\n${entries.join(",\n")},\n]`;
}

/**
 * Writes `src/registry.ts`: one named export per icon holding its raw node
 * data, so `<Icon />` can look up any icon by its converted name and each
 * component in `src/index.ts` reads the one constant it renders.
 */
async function writeRegistryFile(iconNames: string[]) {
	let entries = iconNames
		.map((iconName) => {
			let node = iconNodes[iconName as keyof typeof iconNodes] as unknown as RawIconNode;
			return `export const ${toRegistryExportName(iconName)} = ${renderIconNode(node)} satisfies IconNode;`;
		})
		.join("\n\n");
	let content = `${FILE_HEADER}
import type { IconNode } from "./create-lucide-icon.js";

${entries}
`;
	await writeFile(REGISTRY_FILE, content);
}

/**
 * Writes `src/icon-names.ts`: a compile-time-checked map from each icon's
 * public kebab-case name to its `registry.ts` export name (identifiers can't
 * contain hyphens), plus the `IconName` union used to typecheck `<Icon name />`.
 */
async function writeIconNamesFile(iconNames: string[]) {
	let entries = iconNames
		.map(
			(iconName) =>
				`\t${JSON.stringify(iconName)}: ${JSON.stringify(toRegistryExportName(iconName))},`,
		)
		.join("\n");
	let content = `${FILE_HEADER}
/** Maps each Lucide icon's public kebab-case name to its export name in \`registry.ts\`. */
export const iconExportNames = {
${entries}
} as const;

/** Every valid \`name\` accepted by \`<Icon />\`, matching Lucide's icon catalog (https://lucide.dev/icons/). */
export type IconName = keyof typeof iconExportNames;
`;
	await writeFile(ICON_NAMES_FILE, content);
}

/**
 * Writes `src/index.ts`: the factory, `<Icon />` and every icon component, defined in this one
 * module so a dev server or test runner loads two files for any icon instead of one per icon.
 * Each component is a `#__PURE__` call, so a bundler drops every icon its app never names.
 */
async function writeIndexFile(iconNames: string[]) {
	let components = iconNames
		.map((iconName) => {
			let exportName = `${toPascalCase(iconName)}Icon`;
			let node = `registry.${toRegistryExportName(iconName)}`;
			return `/** Renders the ${JSON.stringify(iconName)} icon from https://lucide.dev/icons/${iconName}. */
export const ${exportName} = /*#__PURE__*/ createLucideIcon(${JSON.stringify(iconName)}, ${node});`;
		})
		.join("\n\n");
	let content = `/**
 * Public entry point for \`@sdxc/icons\` — Lucide icons (https://lucide.dev) as
 * \`remix/component\` components, one tree-shakeable export per icon, matching
 * \`lucide-react\`'s package shape. Generated by \`bun run generate\`; do not edit by hand.
 *
 * @author [Sergio Xalambrí](https://sergiodxa.com)
 * @copyright Sergio Xalambrí 2026
 */

import { createLucideIcon } from "./create-lucide-icon.js";
import * as registry from "./registry.js";

export { createLucideIcon };
export type { IconNode, LucideProps } from "./create-lucide-icon.js";

export { Icon } from "./icon.js";
export type { IconProps } from "./icon.js";

export { iconExportNames } from "./icon-names.js";
export type { IconName } from "./icon-names.js";

${components}
`;
	await writeFile(INDEX_FILE, content);
}

async function main() {
	let iconNames = Object.keys(iconNodes).sort();

	await writeRegistryFile(iconNames);
	await writeIconNamesFile(iconNames);
	await writeIndexFile(iconNames);

	console.log(
		`Generated ${iconNames.length} icons into ${path.relative(PACKAGE_ROOT, INDEX_FILE)}`,
	);
}

await main();
